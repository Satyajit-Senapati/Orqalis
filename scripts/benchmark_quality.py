def distribution(samples: list[float]) -> dict[str, object]:
    ordered = sorted(samples)
    return {
        "samples_ms": samples,
        "median_ms": statistics.median(samples),
        "p95_ms": ordered[math.ceil(len(ordered) * 0.95) - 1],
    }


def timed[ResultT](
    call: Callable[[], ResultT], repetitions: int
) -> tuple[ResultT, dict[str, object]]:
    if repetitions < 1:
        raise ValueError("Timing requires at least one repetition")
    samples = []
    result: ResultT | None = None
    for _ in range(repetitions):
        started = time.perf_counter()
        result = call()
        samples.append((time.perf_counter() - started) * 1000)
    return cast(ResultT, result), distribution(samples)


def unique(values: Iterable[str | None]) -> list[str]:
    return list(dict.fromkeys(value for value in values if value))


def relevance(paths: list[str], expected: list[str], k: int) -> dict[str, object]:
    top = paths[:k]
    hits = set(top) & set(expected)
    gains = [1.0 if path in expected else 0.0 for path in top]
    dcg = sum(gain / math.log2(rank + 2) for rank, gain in enumerate(gains))
    ideal = sum(1 / math.log2(rank + 2) for rank in range(min(k, len(expected))))
    return {
        "top_paths": top,
        "recall_at_k": len(hits) / len(expected) if expected else None,
        "precision_at_k": len(hits) / len(top) if top else 0.0,
        "mrr": next((1 / (rank + 1) for rank, gain in enumerate(gains) if gain), 0.0),
        "ndcg_at_k": dcg / ideal if ideal else None,
        "negative_returned_paths": len(top) if not expected else None,
    }


