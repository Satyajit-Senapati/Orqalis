def digest_files(root: Path, paths: list[str]) -> str:
    digest = hashlib.sha256()
    for relative in sorted(paths):
        digest.update(relative.encode() + b"\0" + (root / relative).read_bytes() + b"\0")
    return digest.hexdigest()


def source_inventory(root: Path) -> list[str]:
    """All package inputs, including new resources; generated bytecode is not source."""
    paths = [
        p.relative_to(root).as_posix()
        for p in (root / "src/orqalis").rglob("*")
        if p.is_file() and "__pycache__" not in p.parts and p.suffix not in {".pyc", ".pyo"}
    ]
    paths += [name for name in ("pyproject.toml", "uv.lock") if (root / name).is_file()]
    return sorted(paths)


def source_fingerprint(root: Path) -> dict[str, object]:
    paths = source_inventory(root)
    return {"files": paths, "sha256": digest_files(root, paths)}


def controlled_environment() -> dict[str, str]:
    env = {
        k: v
        for k, v in os.environ.items()
        if not k.upper().startswith(("ORQALIS_", "PYTHON", "PYTEST", "GIT_"))
    }
    env.update(
        {
            "GIT_CONFIG_NOSYSTEM": "1",
            "GIT_CONFIG_GLOBAL": os.devnull,
            "GIT_NO_REPLACE_OBJECTS": "1",
            "GIT_CONFIG_COUNT": "1",
            "GIT_CONFIG_KEY_0": "core.autocrlf",
            "GIT_CONFIG_VALUE_0": "input",
            "PYTEST_DISABLE_PLUGIN_AUTOLOAD": "1",
        }
    )
    return env


def environment_metadata(repetitions: int) -> dict[str, object]:
    dependencies = sorted(
        {
            (dist.metadata.get("Name", "").lower(), dist.version)
            for dist in importlib.metadata.distributions()
        }
    )
    return {
        "python": sys.version,
        "platform": platform.platform(),
        "machine": platform.machine(),
        "cpu_count": os.cpu_count(),
        "repetitions": repetitions,
        "isolated_python": bool(sys.flags.isolated),
        "dependencies": dependencies,
        "dependency_sha256": hashlib.sha256(json.dumps(dependencies).encode()).hexdigest(),
        "environment_policy": (
            "isolated-source-v3; no inherited ORQALIS/PYTHON/PYTEST/GIT overrides; "
            "no user/system Git config; process-scoped core.autocrlf=input"
        ),
    }


def validate_dataset(dataset: dict[str, Any]) -> None:
    cases = dataset["cases"]
    ids = [case["id"] for case in cases]
    if not ids or len(set(ids)) != len(ids):
        raise ValueError("Dataset requires unique nonempty case IDs")
    paths = dataset["fixture_paths"]
    if len(set(paths)) != len(paths):
        raise ValueError("Dataset fixture paths must be unique")
    for relative in [*paths, *(path for case in cases for path in case["contract_tests"])]:
        path = Path(relative)
        if path.is_absolute() or ".." in path.parts or "\\" in relative:
            raise ValueError("Dataset paths must remain repository-relative")
    if any(path not in paths for case in cases for path in case["relevant_paths"]):
        raise ValueError("Gold paths must exist in the fixed corpus")


def contract_junit(path: Path, required_paths: list[str]) -> dict[str, object]:
    """Count actual JUnit cases; missing, skipped and failed contracts never count as passes."""
    document = ET.parse(path).getroot()
    files = {
        relative: {"passed": 0, "failed": 0, "skipped": 0, "errors": 0}
        for relative in required_paths
    }
    unmatched = []
    total = 0
    seen = set()
    for case in document.iter("testcase"):
        identity = (case.get("classname", ""), case.get("name", ""))
        if identity in seen:
            raise ValueError("Duplicate JUnit testcase identity")
        seen.add(identity)
        total += 1
        matching = [
            relative
            for relative in required_paths
            if identity[0] == relative.removesuffix(".py").replace("/", ".")
            or identity[0].startswith(relative.removesuffix(".py").replace("/", ".") + ".")
        ]
        if len(matching) != 1:
            unmatched.append("::".join(identity))
            continue
        outcome = (
            "errors"
            if case.find("error") is not None
            else "failed"
            if case.find("failure") is not None
            else "skipped"
            if case.find("skipped") is not None
            else "passed"
        )
        files[matching[0]][outcome] += 1
    suite_errors = sum(int(suite.get("errors", "0")) for suite in document.iter("testsuite"))
    return {
        "kind": "deterministic-pytest-contracts",
        "junit_sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
        "files": files,
        "test_count": total,
        "unmatched_cases": unmatched,
        "suite_errors": suite_errors,
        "complete": bool(total)
        and not unmatched
        and not suite_errors
        and all(sum(v.values()) for v in files.values()),
        "passed": bool(total)
        and not unmatched
        and not suite_errors
        and all(
            v["passed"] and not (v["failed"] or v["errors"] or v["skipped"]) for v in files.values()
        ),
        "live_engineering_task_success": None,
    }


def partition_summary(cases: list[dict[str, Any]]) -> dict[str, Any]:
    result: dict[str, Any] = {}
    for partition in sorted({case["partition"] for case in cases}):
        rows = [case for case in cases if case["partition"] == partition]
        result[partition] = {
            "case_count": len(rows),
            "mean_context_bytes": statistics.mean(row["context_bytes"] for row in rows),
        }
        for channel in ("index", "context"):
            positives = [row[channel] for row in rows if row[channel]["recall_at_k"] is not None]
            negatives = [row[channel] for row in rows if row[channel]["recall_at_k"] is None]
            result[partition][channel] = {
                metric: statistics.mean(row[metric] for row in positives) if positives else None
                for metric in ("recall_at_k", "precision_at_k", "mrr", "ndcg_at_k")
            }
            result[partition][channel].update(
                {
                    "positive_cases": len(positives),
                    "negative_cases": len(negatives),
                    "negative_returned_paths": sum(
                        row["negative_returned_paths"] for row in negatives
                    ),
                }
            )
    return result


